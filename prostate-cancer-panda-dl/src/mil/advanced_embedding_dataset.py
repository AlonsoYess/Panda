"""Lazy MIL dataset for advanced tile embedding bags.

The advanced embedding artifacts are produced from ZIPs generated by
``scripts/41_extract_tiles_advanced_batch.py`` and encoded by
``scripts/43_extract_embeddings_from_advanced_tiles.py``. They intentionally do
not need ``encoder_family`` because the contract is controlled by
``encoder_name`` + ``model_name`` + ``embedding_dim``.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, List

import torch
from torch.utils.data import Dataset
from tqdm import tqdm

ENCODER_CONTRACTS: Dict[str, Dict[str, Any]] = {
    "virchow2": {
        "model_names": {"paige-ai/Virchow2"},
        "embedding_dim": 1280,
    },
    "uni2h": {
        "model_names": {"MahmoodLab/UNI2-h"},
        "embedding_dim": 1536,
    },
}


class AdvancedEmbeddingDatasetError(ValueError):
    """Raised when an advanced embedding artifact violates the contract."""


def normalize_encoder_name(encoder_name: str) -> str:
    """Return the canonical lower-case encoder key used by configs."""
    value = str(encoder_name).strip().lower()
    aliases = {
        "virchow2": "virchow2",
        "virchow-2": "virchow2",
        "uni2h": "uni2h",
        "uni2-h": "uni2h",
        "uni2_h": "uni2h",
    }
    if value not in aliases:
        raise AdvancedEmbeddingDatasetError(
            f"encoder_name no soportado: {encoder_name!r}. "
            f"Use uno de: {sorted(ENCODER_CONTRACTS)}."
        )
    return aliases[value]


def expected_dim_for_encoder(encoder_name: str) -> int:
    """Return expected feature dimension for the requested encoder."""
    encoder_key = normalize_encoder_name(encoder_name)
    return int(ENCODER_CONTRACTS[encoder_key]["embedding_dim"])


def _validate_model_name(
    path: Path,
    payload: Dict[str, Any],
    *,
    encoder_key: str,
    expected_model_name: str | None,
) -> None:
    model_name = payload.get("model_name")
    if model_name is None:
        return

    allowed = set(ENCODER_CONTRACTS[encoder_key]["model_names"])
    if expected_model_name is not None:
        allowed.add(str(expected_model_name))
    if str(model_name) not in allowed:
        raise AdvancedEmbeddingDatasetError(
            f"model_name invalido en {path}: esperado uno de {sorted(allowed)}, "
            f"recibido {model_name!r}."
        )


def load_advanced_embedding_payload(
    path: Path,
    *,
    encoder_name: str,
    model_name: str | None = None,
    expected_dim: int | None = None,
    expected_split: str | None = None,
) -> Dict[str, Any]:
    """Load and validate one advanced WSI embedding artifact."""
    artifact_path = Path(path)
    encoder_key = normalize_encoder_name(encoder_name)
    expected_dim = (
        expected_dim_for_encoder(encoder_key)
        if expected_dim is None
        else int(expected_dim)
    )

    try:
        payload = torch.load(
            artifact_path,
            map_location="cpu",
            weights_only=False,
        )
    except Exception as exc:
        raise AdvancedEmbeddingDatasetError(
            f"No se pudo leer el embedding avanzado: {artifact_path}"
        ) from exc

    if not isinstance(payload, dict):
        raise AdvancedEmbeddingDatasetError(
            f"El embedding avanzado debe ser un diccionario: {artifact_path}"
        )
    for key in ("features", "cancer_label"):
        if key not in payload:
            raise AdvancedEmbeddingDatasetError(
                f"Falta {key} en embedding avanzado: {artifact_path}"
            )

    payload_encoder = payload.get("encoder_name")
    if payload_encoder is not None:
        payload_encoder_key = normalize_encoder_name(str(payload_encoder))
        if payload_encoder_key != encoder_key:
            raise AdvancedEmbeddingDatasetError(
                f"encoder_name invalido en {artifact_path}: esperado "
                f"{encoder_key!r}, recibido {payload_encoder!r}."
            )

    _validate_model_name(
        artifact_path,
        payload,
        encoder_key=encoder_key,
        expected_model_name=model_name,
    )

    declared_dim = payload.get("embedding_dim")
    if declared_dim is None:
        raise AdvancedEmbeddingDatasetError(f"Falta embedding_dim en: {artifact_path}")
    if int(declared_dim) != int(expected_dim):
        raise AdvancedEmbeddingDatasetError(
            f"embedding_dim invalido en {artifact_path}: esperado {expected_dim}, "
            f"recibido {declared_dim}."
        )

    features = payload["features"]
    if not isinstance(features, torch.Tensor):
        raise AdvancedEmbeddingDatasetError(f"features no es Tensor en: {artifact_path}")
    if features.ndim != 2:
        raise AdvancedEmbeddingDatasetError(
            f"features debe tener shape [n_tiles, dim] en {artifact_path}; "
            f"shape recibida: {tuple(features.shape)}."
        )
    if int(features.shape[0]) < 1:
        raise AdvancedEmbeddingDatasetError(
            f"tile_count debe ser mayor que cero en: {artifact_path}"
        )
    if int(features.shape[1]) != int(expected_dim):
        raise AdvancedEmbeddingDatasetError(
            f"features.shape[1] invalido en {artifact_path}: esperado "
            f"{expected_dim}, recibido {features.shape[1]}."
        )
    if not torch.isfinite(features).all():
        raise AdvancedEmbeddingDatasetError(
            f"features contiene NaN o Inf en: {artifact_path}"
        )

    tile_count = int(payload.get("tile_count", int(features.shape[0])))
    if tile_count < 1:
        raise AdvancedEmbeddingDatasetError(
            f"tile_count debe ser mayor que cero en: {artifact_path}"
        )
    if tile_count != int(features.shape[0]):
        raise AdvancedEmbeddingDatasetError(
            f"tile_count no coincide con features.shape[0] en {artifact_path}: "
            f"tile_count={tile_count}, features={features.shape[0]}."
        )

    try:
        label = float(payload["cancer_label"])
    except (TypeError, ValueError) as exc:
        raise AdvancedEmbeddingDatasetError(
            f"cancer_label no es numerico en: {artifact_path}"
        ) from exc
    if label not in {0.0, 1.0}:
        raise AdvancedEmbeddingDatasetError(
            f"cancer_label debe ser 0 o 1 en {artifact_path}; recibido {label}."
        )

    if expected_split is not None:
        payload_split = payload.get("split")
        if payload_split is not None and str(payload_split) != str(expected_split):
            raise AdvancedEmbeddingDatasetError(
                f"Split contradictorio en {artifact_path}: carpeta={expected_split!r}, "
                f"metadata={payload_split!r}."
            )

    return payload


class AdvancedEmbeddingDataset(Dataset):
    """Lazy dataset where each item is one variable-size advanced WSI bag."""

    def __init__(
        self,
        embeddings_root: Path,
        split: str,
        *,
        encoder_name: str,
        model_name: str | None = None,
        expected_dim: int | None = None,
        max_items: int | None = None,
        validate_on_init: bool = False,
    ) -> None:
        self.embeddings_root = Path(embeddings_root)
        self.split = str(split)
        self.encoder_name = normalize_encoder_name(encoder_name)
        self.model_name = model_name
        self.expected_dim = (
            expected_dim_for_encoder(self.encoder_name)
            if expected_dim is None
            else int(expected_dim)
        )
        self.split_dir = self.embeddings_root / self.split

        if not self.split_dir.is_dir():
            raise FileNotFoundError(
                f"No existe el directorio de embeddings advanced '{self.split}': "
                f"{self.split_dir}"
            )

        files = sorted(self.split_dir.glob("*.pt"))
        if max_items is not None:
            if int(max_items) < 1:
                raise ValueError("max_items debe ser None o un entero >= 1.")
            files = files[: int(max_items)]
        if not files:
            raise FileNotFoundError(
                f"No se encontraron .pt advanced para split={self.split!r} en "
                f"{self.split_dir}"
            )

        self.files = files
        self.labels: List[float] = []
        self.slide_ids: List[str] = []
        if validate_on_init:
            self.load_labels()

    def load_labels(self) -> List[float]:
        """Load labels after validating artifacts, useful for pos_weight."""
        self.labels = []
        self.slide_ids = []
        for path in tqdm(
            self.files,
            desc=f"Validando advanced/{self.encoder_name}/{self.split}",
            leave=False,
        ):
            payload = load_advanced_embedding_payload(
                path,
                encoder_name=self.encoder_name,
                model_name=self.model_name,
                expected_dim=self.expected_dim,
                expected_split=self.split,
            )
            self.labels.append(float(payload["cancer_label"]))
            self.slide_ids.append(str(payload.get("slide_id", path.stem)))
        return self.labels

    def __len__(self) -> int:
        return len(self.files)

    def __getitem__(self, index: int) -> Dict[str, Any]:
        path = self.files[index]
        payload = load_advanced_embedding_payload(
            path,
            encoder_name=self.encoder_name,
            model_name=self.model_name,
            expected_dim=self.expected_dim,
            expected_split=self.split,
        )
        slide_id = str(payload.get("slide_id", path.stem))
        metadata = {
            "embedding_path": str(path),
            "split": str(payload.get("split", self.split)),
            "encoder_name": payload.get("encoder_name", self.encoder_name),
            "model_name": payload.get("model_name", self.model_name),
            "embedding_dim": int(payload["embedding_dim"]),
            "tile_count": int(payload.get("tile_count", payload["features"].shape[0])),
            "isup_grade": payload.get("isup_grade"),
            "severity_4_label": payload.get("severity_4_label"),
            "gleason_score": payload.get("gleason_score"),
            "tile_ids": list(payload.get("tile_ids", [])),
            "tile_paths": list(payload.get("tile_paths", [])),
            "coordinates": payload.get("coordinates"),
            "selection_rank": payload.get("selection_rank"),
            "tissue_pct": payload.get("tissue_pct"),
            "mask_pct": payload.get("mask_pct"),
            "quality_score": payload.get("quality_score"),
            "histology_score": payload.get("histology_score"),
            "selection_score": payload.get("selection_score"),
            "spatial_region": payload.get("spatial_region"),
            "source_zip": payload.get("source_zip"),
            "source_batch": payload.get("source_batch"),
        }
        return {
            "slide_id": slide_id,
            "features": payload["features"].float(),
            "label": float(payload["cancer_label"]),
            "metadata": metadata,
        }


def advanced_bag_collate_fn(batch: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Collate variable-size WSI bags without padding tile dimensions."""
    return {
        "features": [item["features"] for item in batch],
        "labels": torch.tensor(
            [item["label"] for item in batch],
            dtype=torch.float32,
        ),
        "slide_ids": [item["slide_id"] for item in batch],
        "metadata": [item["metadata"] for item in batch],
    }
